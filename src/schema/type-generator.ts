// Generates TypeScript source from a ModuleSchema: Row/Insert/Update types per
// table, enum unions, and a per-module Tables/Database block that is
// structurally compatible with supabase-js's `createClient<Database>` generic.
import type { ModuleSchema, TableDef, EnumDef } from './types.js';

export function generateTypes(schema: ModuleSchema): string {
  const lines: string[] = [
    `// Generated by supaorm — do not edit by hand.`,
    `// Module: ${schema.moduleId}`,
    '',
  ];

  const enumTypeNames = new Set(schema.enums.map((e) => e.typeName));

  for (const e of schema.enums) {
    lines.push(buildEnumType(e));
    lines.push('');
  }

  for (const t of schema.tables) {
    lines.push(...buildTableTypes(t, enumTypeNames));
    lines.push('');
  }

  lines.push(...buildModuleBlock(schema));

  return lines.join('\n');
}

// ─── Enum ─────────────────────────────────────────────────────────────────────

function buildEnumType(e: EnumDef): string {
  const name = toPascalCase(e.typeName);
  const vals = e.values.map((v) => `'${v}'`).join(' | ');
  return `export type ${name} = ${vals};`;
}

// ─── Table interfaces ─────────────────────────────────────────────────────────

function buildTableTypes(t: TableDef, enumTypeNames: Set<string>): string[] {
  const pascal = toPascalCase(t.tableName);
  const lines: string[] = [];

  // Row type. Must be a `type` alias (object type literal), not an
  // `interface` — interfaces don't get an implicit index signature, so they
  // fail the `Row extends Record<string, unknown>` structural check that
  // supabase-js's GenericTable constraint performs, silently collapsing the
  // whole Schema to `never` and breaking `.from()` typing.
  lines.push(`export type ${pascal}Row = {`);
  for (const [colName, column] of Object.entries(t.columns)) {
    const tsType = pgTypeToTs(column.pgType, enumTypeNames);
    const nullable = column.isNullable ? ' | null' : '';
    lines.push(`  ${colName}: ${tsType}${nullable};`);
  }
  lines.push('};');
  lines.push('');

  // Columns excluded from Insert entirely (generated columns — the DB computes
  // them, so they're not writable) vs columns that become optional on Insert
  // (primary keys with a default, or NOW()-defaulted timestamps).
  const generatedCols = Object.entries(t.columns)
    .filter(([, c]) => c.generatedAs !== null)
    .map(([name]) => name);
  const generatedSet = new Set(generatedCols);
  const autoCols = getAutoColumns(t).filter((name) => !generatedSet.has(name));
  const omitKeys = [...generatedCols, ...autoCols];

  if (omitKeys.length === 0) {
    lines.push(`export type ${pascal}Insert = ${pascal}Row;`);
  } else {
    const omitList = omitKeys.map((c) => `'${c}'`).join(' | ');
    const parts: string[] = [`Omit<${pascal}Row, ${omitList}>`];
    if (generatedCols.length > 0) {
      parts.push(`{ ${generatedCols.map((c) => `${c}?: never`).join('; ')} }`);
    }
    if (autoCols.length > 0) {
      const pickList = autoCols.map((c) => `'${c}'`).join(' | ');
      parts.push(`Partial<Pick<${pascal}Row, ${pickList}>>`);
    }
    lines.push(`export type ${pascal}Insert =`);
    lines.push(`  ${parts.join('\n  & ')};`);
  }
  lines.push('');

  // Update omits the primary key column(s); falls back to 'id' if the table
  // declares no explicit primary key (harmless no-op via Omit if absent).
  const pkCols = Object.entries(t.columns)
    .filter(([, c]) => c.isPrimaryKey)
    .map(([name]) => name);
  const updateOmit = pkCols.length > 0 ? pkCols : ['id'];
  const updateOmitList = updateOmit.map((c) => `'${c}'`).join(' | ');
  lines.push(`export type ${pascal}Update = Partial<Omit<${pascal}Row, ${updateOmitList}>>;`);

  return lines;
}

// ─── Per-module Tables / Database block ───────────────────────────────────────

function buildModuleBlock(schema: ModuleSchema): string[] {
  const modulePascal = toPascalCase(schema.moduleId);
  const lines: string[] = [];

  lines.push(`export type ${modulePascal}Tables = {`);
  for (const t of schema.tables) {
    const pascal = toPascalCase(t.tableName);
    lines.push(
      `  ${t.tableName}: { Row: ${pascal}Row; Insert: ${pascal}Insert; Update: ${pascal}Update; Relationships: [] };`
    );
  }
  lines.push('};');
  lines.push('');

  lines.push(`export type ${modulePascal}Database = {`);
  lines.push(`  public: {`);
  lines.push(`    Tables: ${modulePascal}Tables;`);
  // Views/Functions/CompositeTypes use `{ [_ in never]: never }` rather than
  // `Record<string, never>`. supabase-js's select-query-parser computes
  // `Schema['Tables'] & Exclude<Schema['Views'], ''>` internally — when Views
  // is `Record<string, never>` (an index signature over `string`), that
  // intersection forces every table's properties through the `never` index
  // signature too, collapsing selected rows to `{}`. A mapped type over the
  // `never` key (`{ [_ in never]: never }`) has no index signature, so it
  // intersects as a true no-op empty object instead.
  lines.push(`    Views: { [_ in never]: never };`);
  lines.push(`    Functions: { [_ in never]: never };`);
  if (schema.enums.length > 0) {
    lines.push(`    Enums: {`);
    for (const e of schema.enums) {
      lines.push(`      ${e.typeName}: ${toPascalCase(e.typeName)};`);
    }
    lines.push(`    };`);
  } else {
    lines.push(`    Enums: { [_ in never]: never };`);
  }
  lines.push(`    CompositeTypes: { [_ in never]: never };`);
  lines.push(`  };`);
  lines.push(`};`);

  return lines;
}

// ─── Helpers ──────────────────────────────────────────────────────────────────

function getAutoColumns(t: TableDef): string[] {
  const auto: string[] = [];
  for (const [name, col] of Object.entries(t.columns)) {
    // Any column with a database default is optional on Insert — Postgres
    // fills it when omitted. (Generated columns are handled separately.)
    if (col.defaultExpr != null) {
      auto.push(name);
    }
  }
  return auto;
}

function pgTypeToTs(pgType: string, enumTypeNames: Set<string>): string {
  const upper = pgType.toUpperCase();

  // Enum types
  if (enumTypeNames.has(pgType)) {
    return toPascalCase(pgType);
  }

  // Array types
  if (upper.endsWith('[]')) {
    const base = pgTypeToTs(pgType.slice(0, -2), enumTypeNames);
    return `${base}[]`;
  }

  // Exact matches
  const map: Record<string, string> = {
    UUID: 'string',
    TEXT: 'string',
    DATE: 'string',
    TIME: 'string',
    TIMESTAMPTZ: 'string',
    TIMESTAMP: 'string',
    INTERVAL: 'string', // e.g. '01:30:00' / ISO 8601 duration, serialized as text
    INET: 'string',
    BYTEA: 'string', // base64 (PostgREST default) or hex-encoded ("\\x...") over the wire
    BOOLEAN: 'boolean',
    INTEGER: 'number',
    BIGINT: 'number',
    SMALLINT: 'number',
    NUMERIC: 'number',
    REAL: 'number',
    'DOUBLE PRECISION': 'number',
    JSONB: 'unknown',
    JSON: 'unknown',
  };
  if (map[upper]) return map[upper];

  // Prefix matches
  if (upper.startsWith('DECIMAL') || upper.startsWith('NUMERIC(')) return 'number';
  if (upper.startsWith('VARCHAR')) return 'string';

  // Default fallback
  return 'unknown';
}

// snake_case or mixed → PascalCase
// e.g. pm_task_status → PmTaskStatus, portfolio_theme_configs → PortfolioThemeConfigs
function toPascalCase(s: string): string {
  return s
    .replace(/[^a-zA-Z0-9]+/g, '_')
    .split('_')
    .filter(Boolean)
    .map((word) => word[0].toUpperCase() + word.slice(1).toLowerCase())
    .join('');
}
