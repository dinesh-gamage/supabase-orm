import { describe, expect, it } from 'vitest';
import { createClient } from '@supabase/supabase-js';
import { generateTypes } from '../src/schema/type-generator.js';
import { col, defineSchema, enumType, table } from '../src/schema/builder.js';

// ─── Fixture: a small module exercising every generator rule ─────────────────
// enum, uuid PK w/ default, NOW() timestamps, generatedAs column, nullable +
// notNull columns, FK reference, and the new pg type mappings.

const statusEnum = enumType('demo_status', ['open', 'closed']);

const schema = defineSchema(
  'demo',
  [
    table('demo_owners', {
      id: col.uuid().primaryKey().default('gen_random_uuid()'),
      name: col.text().notNull(),
    }),
    table('demo_items', {
      id: col.uuid().primaryKey().default('gen_random_uuid()'),
      status: col.enum('demo_status').notNull(),
      title: col.text().notNull(),
      description: col.text().nullable(),
      owner_id: col.uuid().nullable().references('demo_owners', 'id', { onDelete: 'SET NULL' }),
      payload: col.bytea().nullable(),
      last_ip: col.inet().nullable(),
      active_for: col.interval().nullable(),
      rating: col.real().nullable(),
      weight: col.doublePrecision().nullable(),
      line_total: col.integer().generatedAs('quantity * unit_price'),
      created_at: col.timestamptz().notNull().default('NOW()'),
      updated_at: col.timestamptz().notNull().default('NOW()'),
    }),
  ],
  [statusEnum]
);

const output = generateTypes(schema);

describe('generateTypes', () => {
  it('emits a neutral header with no reference to any other project', () => {
    expect(output.startsWith('// Generated by supaorm — do not edit by hand.')).toBe(true);
    expect(output.toLowerCase()).not.toContain('life-grid');
  });

  it('maps Row nullability from isNullable', () => {
    expect(output).toContain('  title: string;');
    expect(output).toContain('  description: string | null;');
  });

  it('maps enum columns to the PascalCase enum union type', () => {
    expect(output).toContain('  status: DemoStatus;');
  });

  it('emits the enum union type', () => {
    expect(output).toContain(`export type DemoStatus = 'open' | 'closed';`);
  });

  it('applies the new pg type mappings: bytea/inet/interval/real/double precision', () => {
    expect(output).toContain('  payload: string | null;'); // bytea
    expect(output).toContain('  last_ip: string | null;'); // inet
    expect(output).toContain('  active_for: string | null;'); // interval
    expect(output).toContain('  rating: number | null;'); // real
    expect(output).toContain('  weight: number | null;'); // double precision
  });

  it('excludes generated columns from Insert via Omit + `?: never`, and makes defaulted/nullable columns optional', () => {
    expect(output).toContain(
      `export type DemoItemsInsert =\n  Omit<DemoItemsRow, 'line_total' | 'id' | 'description' | 'owner_id' | 'payload' | 'last_ip' | 'active_for' | 'rating' | 'weight' | 'created_at' | 'updated_at'>\n  & { line_total?: never }\n  & Partial<Pick<DemoItemsRow, 'id' | 'description' | 'owner_id' | 'payload' | 'last_ip' | 'active_for' | 'rating' | 'weight' | 'created_at' | 'updated_at'>>;`
    );
  });

  it('keeps generated columns non-nullable in Row (generatedAs forces NOT NULL)', () => {
    expect(output).toContain('  line_total: number;');
  });

  it('makes the sole PK-with-default column optional on a table with no other auto columns', () => {
    expect(output).toContain(
      `export type DemoOwnersInsert =\n  Omit<DemoOwnersRow, 'id'>\n  & Partial<Pick<DemoOwnersRow, 'id'>>;`
    );
  });

  it('Update omits the primary key', () => {
    expect(output).toContain('export type DemoItemsUpdate = Partial<Omit<DemoItemsRow, \'id\'>>;');
    expect(output).toContain('export type DemoOwnersUpdate = Partial<Omit<DemoOwnersRow, \'id\'>>;');
  });

  it('emits a TablesMap + Database block per module (snapshot)', () => {
    expect(output).toContain(
      [
        'export type DemoTables = {',
        '  demo_owners: { Row: DemoOwnersRow; Insert: DemoOwnersInsert; Update: DemoOwnersUpdate; Relationships: [] };',
        '  demo_items: { Row: DemoItemsRow; Insert: DemoItemsInsert; Update: DemoItemsUpdate; Relationships: [] };',
        '};',
      ].join('\n')
    );

    expect(output).toContain(
      [
        'export type DemoDatabase = {',
        '  public: {',
        '    Tables: DemoTables;',
        '    Views: { [_ in never]: never };',
        '    Functions: { [_ in never]: never };',
        '    Enums: {',
        '      demo_status: DemoStatus;',
        '    };',
        '    CompositeTypes: { [_ in never]: never };',
        '  };',
        '};',
      ].join('\n')
    );
  });

  it('emits { [_ in never]: never } (not Record<string, never>) for Views/Functions/CompositeTypes when there are no enums either', () => {
    const noEnumSchema = defineSchema('bare', [
      table('bare_things', {
        id: col.uuid().primaryKey().default('gen_random_uuid()'),
        label: col.text().notNull(),
      }),
    ]);
    const noEnumOutput = generateTypes(noEnumSchema);
    expect(noEnumOutput).toContain('    Enums: { [_ in never]: never };');
  });
});

// ─── Type-level compile check ──────────────────────────────────────────────────
// A hand-written interface using the same conventions the generator emits,
// passed to supabase-js's createClient<Database> generic. This only needs to
// typecheck (`npx tsc --noEmit`) — it is never awaited, so no network call is
// made when this test file runs.

type DemoOwnersRow = { id: string; name: string };
type DemoOwnersInsert = Omit<DemoOwnersRow, 'id'> & Partial<Pick<DemoOwnersRow, 'id'>>;
type DemoOwnersUpdate = Partial<Omit<DemoOwnersRow, 'id'>>;

type DemoStatus = 'open' | 'closed';
type DemoItemsRow = {
  id: string;
  status: DemoStatus;
  title: string;
  description: string | null;
  owner_id: string | null;
  payload: string | null;
  last_ip: string | null;
  active_for: string | null;
  rating: number | null;
  weight: number | null;
  line_total: number;
  created_at: string;
  updated_at: string;
};
type DemoItemsInsert = Omit<DemoItemsRow, 'line_total' | 'id' | 'created_at' | 'updated_at'> & {
  line_total?: never;
} & Partial<Pick<DemoItemsRow, 'id' | 'created_at' | 'updated_at'>>;
type DemoItemsUpdate = Partial<Omit<DemoItemsRow, 'id'>>;

type HandDatabase = {
  public: {
    Tables: {
      demo_owners: { Row: DemoOwnersRow; Insert: DemoOwnersInsert; Update: DemoOwnersUpdate; Relationships: [] };
      demo_items: { Row: DemoItemsRow; Insert: DemoItemsInsert; Update: DemoItemsUpdate; Relationships: [] };
    };
    Views: { [_ in never]: never };
    Functions: { [_ in never]: never };
    Enums: { demo_status: DemoStatus };
    CompositeTypes: { [_ in never]: never };
  };
};

describe('generated Database shape is compatible with supabase-js createClient<Database>', () => {
  it('compiles and infers Row/Insert types through the client (not `never`/`{}`)', () => {
    const client = createClient<HandDatabase>('http://localhost', 'anon-key');

    // Not awaited — construction only, to prove the generics resolve correctly.
    void client.from('demo_items').select('*');
    void client
      .from('demo_items')
      .insert({
        title: 't',
        status: 'open',
        description: null,
        owner_id: null,
        payload: null,
        last_ip: null,
        active_for: null,
        rating: null,
        weight: null,
      })
      .select()
      .single();
    void client.from('demo_owners').update({ name: 'x' }).eq('id', '1').select().single();

    expect(true).toBe(true);
  });
});
